import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const moduleDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(moduleDirectory, "..");
const locationsDirectory = path.join(repositoryRoot, "data", "locations");
const outputJsonPath = path.join(repositoryRoot, "data", "reference", "openbible-ids.json");
const outputTypeScriptPath = path.join(
  repositoryRoot,
  "app",
  "src",
  "features",
  "place-panel",
  "openbible-ids.generated.ts"
);

const openBibleAncientDatasetUrl =
  "https://raw.githubusercontent.com/openbibleinfo/Bible-Geocoding-Data/main/data/ancient.jsonl";
const openBibleAncientPageUrlPrefix = "https://www.openbible.info/geo/ancient";

function collectOpenBibleSources(locationRecord) {
  const sourceIds = [];

  function ingestSources(sources) {
    if (!Array.isArray(sources)) {
      return;
    }

    for (const sourceId of sources) {
      if (typeof sourceId !== "string" || !sourceId.startsWith("openbible:")) {
        continue;
      }
      sourceIds.push(sourceId.slice("openbible:".length));
    }
  }

  ingestSources(locationRecord.summary?.sources);
  for (const candidate of locationRecord.candidates ?? []) {
    ingestSources(candidate?.sources);
  }
  for (const historyEntry of locationRecord.history ?? []) {
    ingestSources(historyEntry?.sources);
  }
  for (const otConnection of locationRecord.otConnections ?? []) {
    ingestSources(otConnection?.sources);
  }
  for (const politicalHistoryEntry of locationRecord.politicalHistory ?? []) {
    ingestSources(politicalHistoryEntry?.sources);
  }

  return sourceIds;
}

async function collectUsedOpenBibleSlugs() {
  const entries = await fs.readdir(locationsDirectory, { withFileTypes: true });
  const locationFiles = entries
    .filter((entry) => entry.isFile() && entry.name.toLowerCase().endsWith(".json"))
    .map((entry) => path.join(locationsDirectory, entry.name))
    .sort((left, right) => left.localeCompare(right));

  const slugs = new Set();

  for (const filePath of locationFiles) {
    const locationRecord = JSON.parse(await fs.readFile(filePath, "utf8"));
    for (const slug of collectOpenBibleSources(locationRecord)) {
      slugs.add(slug);
    }
  }

  return [...slugs].sort((left, right) => left.localeCompare(right));
}

async function fetchOpenBibleSlugToIdMap() {
  const response = await fetch(openBibleAncientDatasetUrl, {
    headers: {
      "user-agent": "interactive-bible-map-openbible-builder"
    }
  });
  if (!response.ok) {
    throw new Error(
      `Could not download OpenBible ancient dataset (${response.status} ${response.statusText}).`
    );
  }

  const datasetText = await response.text();
  const slugToId = new Map();

  for (const rawLine of datasetText.split(/\r?\n/gu)) {
    const line = rawLine.trim();
    if (line.length === 0) {
      continue;
    }

    const record = JSON.parse(line);
    if (
      typeof record?.url_slug !== "string" ||
      record.url_slug.length === 0 ||
      typeof record?.id !== "string" ||
      record.id.length === 0
    ) {
      continue;
    }

    slugToId.set(record.url_slug, record.id);
  }

  return slugToId;
}

function ancientPlaceUrl(id, slug) {
  return `${openBibleAncientPageUrlPrefix}/${id}/${encodeURIComponent(slug)}`;
}

function toOpenBibleIdsObject(slugs, slugToIdMap) {
  const missingSlugs = [];
  const resolved = {};

  for (const slug of slugs) {
    const id = slugToIdMap.get(slug);
    if (!id) {
      missingSlugs.push(slug);
      continue;
    }

    resolved[slug] = id;
  }

  return {
    resolved,
    missingSlugs
  };
}

async function verifyResolvedOpenBibleUrls(resolvedSlugToId) {
  const failed = [];

  for (const [slug, id] of Object.entries(resolvedSlugToId)) {
    const url = ancientPlaceUrl(id, slug);
    const response = await fetch(url, {
      redirect: "follow",
      headers: {
        "user-agent": "interactive-bible-map-openbible-builder"
      }
    });

    if (response.status !== 200) {
      failed.push({
        slug,
        id,
        url,
        status: response.status
      });
    }
  }

  return failed;
}

function toGeneratedTypeScript(resolvedSlugToId) {
  const jsonObject = JSON.stringify(resolvedSlugToId, null, 2);
  return `// Generated by scripts/build-openbible-ids.mjs from data/reference/openbible-ids.json.\n// Do not edit this file by hand.\n\nexport const OPENBIBLE_IDS_BY_SLUG: Readonly<Record<string, string>> = Object.freeze(${jsonObject});\n`;
}

async function writeOutputs(resolvedSlugToId) {
  await fs.mkdir(path.dirname(outputJsonPath), { recursive: true });
  await fs.mkdir(path.dirname(outputTypeScriptPath), { recursive: true });
  await fs.writeFile(`${outputJsonPath}`, `${JSON.stringify(resolvedSlugToId, null, 2)}\n`, "utf8");
  await fs.writeFile(outputTypeScriptPath, toGeneratedTypeScript(resolvedSlugToId), "utf8");
}

async function run() {
  const usedSlugs = await collectUsedOpenBibleSlugs();
  const slugToIdMap = await fetchOpenBibleSlugToIdMap();
  const { resolved, missingSlugs } = toOpenBibleIdsObject(usedSlugs, slugToIdMap);
  const failedLiveChecks = await verifyResolvedOpenBibleUrls(resolved);

  await writeOutputs(resolved);

  console.log(
    `Resolved ${Object.keys(resolved).length} OpenBible slug(s) from ${usedSlugs.length} used in data/locations.`
  );

  if (missingSlugs.length > 0) {
    console.warn(
      `Missing slug(s): ${missingSlugs.map((slug) => `openbible:${slug}`).join(", ")}`
    );
    console.warn("Panel formatter will fall back to https://www.openbible.info/geo/ for these.");
  }

  if (failedLiveChecks.length > 0) {
    console.warn(
      `Live URL check failures: ${JSON.stringify(failedLiveChecks, null, 2)}`
    );
  }

  if (missingSlugs.length > 0 || failedLiveChecks.length > 0) {
    process.exitCode = 1;
  }
}

await run();
